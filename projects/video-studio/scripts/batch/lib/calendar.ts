/**
 * calendar --from <week> --weeks <n>: the content calendar as Markdown (docs/CONTENT_CALENDAR.md), made by the same
 * planner as `plan`, so the calendar, the week plans and the review pages always agree. Deterministic: no clock, so
 * `--check` can tell whether the committed file still matches the backlogs and the settings.
 */
import type {Backlog, BatchConfig, Idea, PlanItem} from './types.ts';
import {assignWeeks, buildItems, orderedSlots} from './schedule.ts';
import {addDays, addWeeks, DAYS, type IsoWeek, mondayOf, parseWeek, shortDate} from './week.ts';
import {cell} from './writer.ts';
import {formatUtcTime, zoneAbbr, zonedToUtc} from './zone.ts';

export type CalendarInput = {config: BatchConfig; backlogs: Backlog[]; from: IsoWeek; weeks: number; researchExists: (path: string) => boolean; command: string};

const FORMAT_NAMES: Record<string, string> = {'pov-story': 'POV story', explainer: 'Explainer', 'scam-of-the-week': 'Scam of the Week'};

/** Where an idea's facts stand: its own research file, checked leads elsewhere, or nothing yet. */
export const factsLabel = (idea: Idea, hasResearchFile: boolean): string => {
	const total = idea.facts.length;
	const needed = idea.facts.filter((f) => f.status === 'research needed').length;
	const bank = idea.facts.filter((f) => f.status === 'fact-bank').length;
	const leads = idea.facts.filter((f) => f.status === 'researched').length;
	if (bank === total) return 'all in the fact bank';
	const inBank = bank ? `${bank} of ${total} in the fact bank` : '';
	if (hasResearchFile) return [`research file`, inBank, needed ? `${needed} still to research` : bank ? '' : 'move its facts into the bank'].filter(Boolean).join('; ');
	if (!leads && !bank) return `research first: ${total} facts to find`;
	return [`research first`, inBank, leads ? `${leads} with checked leads` : '', needed ? `${needed} to find` : ''].filter(Boolean).join('; ');
};

const dayLabel = (date: string) => `${DAYS[(new Date(`${date}T00:00:00Z`).getUTCDay() + 6) % 7]} ${shortDate(date)}`;

export const renderCalendar = (c: CalendarInput): string => {
	const {config} = c;
	const last = addWeeks(c.from, c.weeks - 1);
	const assignments = assignWeeks(config, c.backlogs, c.from, last);
	const ideaOf = (item: PlanItem) => c.backlogs.find((b) => b.channel === item.channel)?.ideas.find((i) => i.id === item.ideaId);
	const firstMonday = mondayOf(c.from);
	const lastSunday = addDays(mondayOf(last), 6);
	const zoneAt = (date: string) => {
		const r = zonedToUtc(date, '12:00', config.timeZone);
		return r.ok ? zoneAbbr(r.ms, config.timeZone) : config.timeZone;
	};
	const zones = [...new Set([firstMonday, lastSunday].map(zoneAt))];
	const out: string[] = [];
	out.push(`# Content calendar: ${c.weeks} weeks from ${shortDate(firstMonday, true)} (proposal)`, '');
	out.push(
		"> **Proposal, pending the owner's approval.** Nothing in this calendar is approved, scheduled or uploaded. Every upload needs the owner's explicit approval on the weekly page (docs/PROJECT_INSTRUCTIONS.md: \"Do not upload or publish the video unless I request that separately\"). Dates, times, formats, lengths and the order of topics are all proposals.",
		'',
		`Generated by \`${c.command}\` from ${c.backlogs.map((b) => `\`${b.path}\``).join(', ')} and \`${config.path}\`. Edit those and regenerate; \`--check\` fails when this file no longer matches them. How the weekly batch works: [WEEKLY_BATCH.md](WEEKLY_BATCH.md).`,
		'',
	);

	out.push('## How the weeks are built', '');
	out.push(`- **Times** are ${config.timeZone}, the owner's time zone (CLAUDE.md, owner decisions). This period is ${zones.join(' and ')}${zones.length === 1 && zones[0] === 'CST' ? ' (UTC−6) throughout' : ''}; each slot also shows UTC.`);
	for (const ch of config.channels) {
		const slots = orderedSlots(ch);
		const longs = slots.map((s) => `${s.day} ${s.time} (${s.formats.map((f) => FORMAT_NAMES[f] ?? f).join(' or ')})`).join(', ');
		out.push(`- **${ch.name}** (\`${ch.channel}\`): ${slots.length} long-form slots a week, ${longs}${ch.shorts ? `, and a Short at ${ch.shorts.time} ${ch.shorts.days.length === 7 ? 'every day' : `on ${ch.shorts.days.join(', ')}`}, cut from the latest episode of the week published before it` : ''}.`);
	}
	out.push('- **Order:** ideas fill the slots in backlog priority order; an idea pinned to a week (`"week"` in the backlog) takes that week first. `plan` pins what it places, so the next week never repeats it.');
	out.push(
		'- **The daily Threat Brief** (the security channel\'s daily news Short) stays daily and is not in this calendar: scripts/daily, about 5 minutes of review a day.',
		'- **Languages:** every item is written and voiced in English; Spanish (`es`) and Brazilian Portuguese (`pt-br`) go on the same video as multi-language audio tracks (a Studio step), with localized titles and descriptions. A dub track goes up only after its claim gate passes and a native review.',
		'- **One review sitting a week:** the week\'s items arrive on one approval page (`review`). Approve by the Sunday before the week: the uploader refuses a publish time less than 60 minutes away, and every item goes up private, scheduled for its slot.',
		'- **After each long episode publishes:** the article, podcast, X thread, Telegram post, LinkedIn post and newsletter drafts (scripts/assets, docs/ASSETS.md), for the owner to review before anything is posted.',
		'',
	);

	for (const wa of assignments) {
		const week = parseWeek(wa.week) as IsoWeek;
		const monday = mondayOf(week);
		const {items, warnings} = buildItems(config, wa, c.researchExists);
		out.push(`## Week ${week.week}: ${dayLabel(monday)} to ${dayLabel(addDays(monday, 6))} ${addDays(monday, 6).slice(0, 4)} (\`${wa.week}\`)`, '');
		out.push(`Production in the days before; review sitting by ${dayLabel(addDays(monday, -1))}.`, '');
		out.push('| Date | Time | UTC | Channel | Item | What | Title or angle | Topic | Languages | Facts |', '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |');
		for (const item of items) {
			const idea = ideaOf(item);
			const note = config.dateNotes[item.slot.date];
			out.push(
				`| ${dayLabel(item.slot.date)}${note ? ` (${cell(note)})` : ''} | ${item.slot.time} | ${formatUtcTime(Date.parse(item.slot.publishAt)).replace(' UTC', '')} | ${cell(item.channelName)} | \`${item.id}\` | ${item.kind === 'long' ? cell(FORMAT_NAMES[item.format] ?? item.format) : `Short ${item.shortIndex} of \`${item.parentId}\``} | ${cell(item.title)} | ${idea ? `\`${idea.evergreenTopic}\`` : ''} | ${['en', ...item.languages.dubs].join(', ')} | ${idea && item.kind === 'long' ? cell(factsLabel(idea, !!item.research.file)) : ''} |`,
			);
		}
		for (const ch of config.channels) {
			for (const r of ch.reserved ?? []) {
				const date = r.day ? addDays(monday, DAYS.indexOf(r.day)) : null;
				const utc = date && r.time ? (() => {
					const z = zonedToUtc(date, r.time, config.timeZone);
					return z.ok ? formatUtcTime(z.ms).replace(' UTC', '') : '';
				})() : '';
				out.push(`| ${date ? dayLabel(date) : 'Day TBD (owner)'} | ${r.time ?? 'TBD'} | ${utc || 'TBD'} | ${cell(ch.name)} | reserved | ${cell(r.label)} | Made in-week, not by the batch | | en | |`);
			}
		}
		out.push('');
		const longs = items.filter((i) => i.kind === 'long');
		const pilots = longs.filter((l) => /^pilot\b/i.test(ideaOf(l)?.role ?? ''));
		for (const p of pilots) {
			const format = config.channels.find((ch) => ch.channel === p.channel)?.formats[p.format];
			out.push(`**Pilot:** \`${p.id}\` is the pilot. CLAUDE.md (Status, Phase 2) defines the pilot as a 60–90 s video with 1 Short, 3 thumbnails and publish.md, then an owner review; this calendar plans it as a ${cell(format?.label ?? p.format)} (${cell((format?.length ?? 'TBD').replace(/\s*\(proposal\)/i, ''))}) with ${p.shortIds.length} Short(s). The owner decides which (see the decisions at the end).`, '');
		}
		const withShorts = longs.filter((l) => l.shortIds.length);
		if (withShorts.length) out.push(`**Shorts map:** ${withShorts.map((l) => `\`${l.id}\` → ${l.shortIds.map((s) => `\`${s}\` (${items.find((x) => x.id === s)?.slot.day ?? '?'})`).join(', ')}`).join(' · ')}`, '');
		const holidays = [...new Set(items.map((i) => i.slot.date))].filter((d) => config.dateNotes[d]);
		if (holidays.length) out.push(`**Owner check:** ${holidays.map((d) => `${dayLabel(d)} is ${config.dateNotes[d]}`).join('; ')}. Keep, move or skip those slots.`, '');
		if (warnings.length || wa.warnings.length) out.push(...[...wa.warnings, ...warnings].map((w) => `- Warning: ${cell(w)}`), '');
	}

	const usedIds = new Set(assignments.flatMap((wa) => wa.channels.flatMap((x) => x.slots.filter((i): i is Idea => !!i).map((i) => `${x.channel}/${i.id}`))));
	out.push(`## Not scheduled in these ${c.weeks} weeks (backlog order)`, '');
	out.push('| Channel | Priority | Idea | What | Topic | Facts |', '| --- | --- | --- | --- | --- | --- |');
	for (const b of c.backlogs) {
		const name = config.channels.find((x) => x.channel === b.channel)?.name ?? b.channel;
		const rest = b.ideas
			.map((idea, index) => ({idea, index}))
			.filter(({idea}) => !usedIds.has(`${b.channel}/${idea.id}`) && idea.status === 'idea')
			.sort((x, y) => x.idea.priority - y.idea.priority || x.index - y.index);
		for (const {idea} of rest) out.push(`| ${cell(name)} | ${idea.priority} | ${cell(idea.title)} | ${cell(FORMAT_NAMES[idea.format] ?? idea.format)} | \`${idea.evergreenTopic}\` | ${cell(factsLabel(idea, c.researchExists(idea.research ?? `content/${b.channel}/${idea.slug}/research.md`)))} |`);
	}
	out.push('');

	out.push('## Decisions this calendar needs from the owner', '');
	const lengths = config.channels.flatMap((ch) => Object.values(ch.formats).map((f) => `${f.label} ${f.length.replace(/\s*\(proposal\)/i, '')}`));
	out.push(
		'- Approve this calendar, or change it: reorder `priority` in a backlog, pin an idea to a week (`"week": "2026-W50"`), or move a slot in scripts/batch/config.json, then regenerate.',
		'- The publish days and times above.',
		`- Long-form lengths (proposed: ${[...new Set(lengths)].join('; ')}).`,
		'- The YouTube category for each channel (`categoryId` in creator-hub/tools/uploader/channels.json): approve is refused until it is set.',
		"- The security channel's display name (TBD; the show name stands in).",
		'- Who reviews the Spanish and Brazilian Portuguese dubs natively before their tracks go up.',
		...config.channels.flatMap((ch) => (ch.reserved ?? []).filter((r) => !r.day).map((r) => `- The day and time of ${cell(ch.name)}'s ${cell(r.label.replace(/\s*\(.*\)$/, '').toLowerCase())}: every week above keeps a reserved row for it. ${cell(r.note)}`)),
		...c.backlogs.flatMap((b) =>
			b.ideas
				.filter((i) => /^pilot\b/i.test(i.role ?? '') && i.status === 'idea')
				.map((i) => `- The pilot's format (\`${i.id}\`): CLAUDE.md's Phase 2 is a 60–90 s pilot with 1 Short, 3 thumbnails and publish.md, followed by an owner review before the next phase. This calendar plans it as a full ${cell(FORMAT_NAMES[i.format] ?? i.format)} with daily Shorts. Either keep the short pilot first (this calendar then starts after its review), or approve the full-length version.`),
		),
		'',
	);
	return out.join('\n');
};
