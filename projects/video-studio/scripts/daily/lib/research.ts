/**
 * research.md for a daily news episode. The general claim gate (scripts/claims/check.ts) requires one next to every
 * storyboard, with a "## Must not say" section it turns into banned phrases. Its parser bans QUOTED phrases, so only
 * phrases that are really banned are quoted here; everything else is plain guidance (listed for a human read).
 * Feed text never goes inside quotes here, so a headline can never become a ban or an instruction.
 */
import type {DailyBrief} from './types.ts';
import {isAiStory} from './types.ts';

const MD_UNSAFE = /[`*_[\]<>#|!~"'“”‘’]/g;
/** Feed text in research.md: no quotes (they would become bans), no markup. */
const flat = (s: string): string => s.replace(MD_UNSAFE, ' ').replace(/\s+/g, ' ').trim();

export const renderResearchMd = (b: DailyBrief): string => {
	const o: string[] = [];
	o.push(`# Research: ${b.slug}`, '');
	o.push(
		`Generated by \`node scripts/daily/run.ts prepare\` on ${b.generatedAt} from the radar file ${b.radar.path}. The facts, the stored excerpts and the analysis data are in brief.json; WRITER.md is the writer's guide. Status: **${b.status.toUpperCase()}** (${flat(b.incident.statusReason ?? '')}).`,
		'',
	);
	o.push('## Story', '');
	o.push(`- Incident: ${flat(b.incident.protocol)}, ${b.incident.type}, dated ${b.incident.dateUtc || 'unknown'}${b.incident.chains.length ? `, chains ${flat(b.incident.chains.join(', '))}` : ''}.`);
	if (b.evergreen) o.push(`- Evergreen topic: ${b.evergreen.topic} (${flat(b.evergreen.title)}).`);
	for (const l of b.reportedLosses) o.push(`- Loss figure as stored: ${flat(l.quote)}, reported by ${flat(l.publisher)} (tier ${l.tier}).`);
	o.push('');
	o.push('## Sources', '');
	for (const s of b.sources) o.push(`- ${flat(s.publisher)} (tier ${s.tier}, ${s.kind}): ${flat(s.title)}. ${s.url}`);
	o.push('');
	o.push('## Must not say', '');
	o.push(
		`- Any individual's name, handle or likeness: suspects, victims, founders, investigators.${b.sources.some((s) => s.redactedNames) ? ' The radar redacted names in this story; never fill them in.' : ''}`,
		'- "probably", "likely", "rumoured", "insiders say", "must have been", "sources close to"',
		'- "price target", "buy the dip", "to the moon", "guaranteed returns", "not too late to buy"',
		'- "proven guilty", "convicted hacker", "criminal mastermind" (filings and allegations are not findings)',
		'- An averaged, summed or merged loss figure. Each figure goes with its own source.',
		'- Code, addresses, transaction hashes, function or contract names, payloads, or a step-by-step attack sequence.',
		"- Screenshots, redrawn charts, logos or images of other people's posts or dashboards.",
		'- A state or threat group named without an attribution to a source in the same sentence, or named in a title or thumbnail.',
		'- Anything from X or Telegram posts: they were not read.',
	);
	for (const m of b.mustNotSay.filter((x) => x.rule === 'hedge')) {
		const s = b.sources.find((x) => m.text.startsWith(x.publisher));
		if (s?.hedge) o.push(`- ${flat(s.publisher)}'s hedged wording (${flat(s.hedge)}) stated as fact. Repeat it only attributed, with the hedge.`);
	}
	if (isAiStory(b.incident))
		o.push('- AI story: any prompt, injected instruction, jailbreak text, payload, malicious skill or plugin, or the wording or setting that got past a safeguard, quoted or paraphrased. Name products and companies, never the researchers, employees or victims.');
	if (b.sources.some((s) => s.listedReport))
		o.push('- Anything taken from an incident database listing (the AI Incident Database): it lists other outlets\' reports the radar never read. Never cite it, even next to another source.');
	if (b.status === 'developing') o.push('- Any claim about this incident before the line that says it is a developing story.');
	o.push('');
	return o.join('\n');
};
