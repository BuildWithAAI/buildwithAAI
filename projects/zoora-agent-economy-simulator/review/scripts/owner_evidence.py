"""Actual CLI and independent AE-018 owner capacity/exposure evidence."""
from __future__ import annotations
import copy
import csv
import gzip
import hashlib
import io
import json
import os
import platform
import subprocess
import sys
import tempfile
import time
from pathlib import Path
from owner_audit import inspect_campaign, inspect_run, run_hash, campaign_hash, POLICIES

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "target/validation-evidence"
OUT.mkdir(parents=True, exist_ok=True)
NAME = "zoora-review-market" + (".exe" if os.name == "nt" else "")
EXPECTED = "3a86e0ff3aa16bd77f4381c22d02017d7ce57ca5ba8b877c93aa8f3b3c2d3459"
CHECKS = []


def check(label, condition=True):
    assert condition, label
    CHECKS.append(label)


def cli(*args, profile="release", ok=True):
    p = subprocess.run([str(ROOT / "target" / profile / NAME), *map(str, args)],
                       cwd=ROOT, text=True, capture_output=True, timeout=120)
    assert (p.returncode == 0) == ok, (args, p.stdout[-500:], p.stderr[-1500:])
    return p


def rejects(audit, value):
    try:
        audit(value)
    except (AssertionError, KeyError, IndexError):
        return
    raise AssertionError("independent auditor accepted modified history")


start = time.perf_counter()
with tempfile.TemporaryDirectory() as folder:
    temp = Path(folder)
    campaign = OUT / "owner-campaign.json"
    cli("owner-campaign", ROOT / "configs/owner-campaign.toml", campaign)
    cli("replay-owner-campaign", campaign)
    data = json.loads(campaign.read_bytes())
    counts = inspect_campaign(data)
    check("13 matched scenarios and all 39 histories independently audited", counts["policy_runs"] == 39)
    check("reference campaign fingerprint is pinned", data["fingerprint"] == EXPECTED)
    check("retained complete archive equals regenerated bytes",
          gzip.decompress((ROOT / "examples/owner-campaign.json.gz").read_bytes()) == campaign.read_bytes())
    debug = temp / "debug.json"
    cli("owner-campaign", ROOT / "configs/owner-campaign.toml", debug, profile="debug")
    check("normal and optimized builds produce identical histories", debug.read_bytes() == campaign.read_bytes())
    runs = {(c["name"], r["input"]["policy"]): r for c in data["cases"] for r in c["runs"]}
    for (name, policy), run in runs.items():
        source, output = temp / (name + policy + "-input.json"), temp / (name + policy + ".json")
        source.write_text(json.dumps(run["input"]), encoding="utf-8")
        cli("owner-run", source, output)
        cli("replay-owner", output)
        value = json.loads(output.read_bytes())
        assert value == run
        inspect_run(value)
        check(name + "/" + policy + " actual CLI reproduces full history")
    export = OUT / "owner-campaign.csv"
    cli("owner-csv", campaign, export)
    rows = list(csv.DictReader(io.StringIO(export.read_text(encoding="utf-8"))))
    expected_rows = []
    for c in data["cases"]:
        for r in c["runs"]:
            for o in r["owners"]:
                row = dict(case=c["name"], classification="SYNTHETIC", policy=r["input"]["policy"])
                for k, v in o.items():
                    if k == "agents":
                        row[k] = ";".join(map(str, v))
                    elif k == "active_agreements":
                        row[k] = str(len(v))
                    elif isinstance(v, bool):
                        row[k] = str(v).lower()
                    else:
                        row[k] = str(v)
                for col, key in [("owner_rejections", "owner_rejections"), ("delegated_rejections", "delegated_rejections"),
                                 ("agreements_opened", "agreements_opened"), ("total_payments", "payments_recorded"),
                                 ("total_returns", "voluntary_returns_recorded"), ("total_net", "net_transferred")]:
                    row["run_" + col] = str(r["metrics"][key])
                row.update(run_fingerprint=r["fingerprint"], campaign_fingerprint=data["fingerprint"])
                expected_rows.append(row)
    check("every CSV owner row exactly matches source fields and scoped run totals", rows == expected_rows)
    check("retained CSV equals actual export", export.read_bytes() == (ROOT / "examples/owner-campaign.csv").read_bytes())
    run = lambda n, p="OWNER_RISK": runs[n, p]
    owner = lambda r, op=0: next(o for o in r["owners"] if o["operator"] == op)
    agreements = lambda n, p="OWNER_RISK": run(n, p)["metrics"]["agreements_opened"]
    check("declared aliases share one starter work slot",
          agreements("DECLARED_WALLET_ROTATION", "AGENT_ONLY") == 3 and agreements("DECLARED_WALLET_ROTATION") == 1)
    check("a single large promise is refused before payment",
          agreements("LARGE_SINGLE_OBLIGATION", "OWNER_COUNT") == 1 and agreements("LARGE_SINGLE_OBLIGATION") == 0)
    check("best current member tier is used without adding aliases' capacities",
          owner(run("TIERED_OWNER_CAPACITY"))["work_limit"] == 2 and owner(run("TIERED_OWNER_CAPACITY"))["payment_limit"] == 300)
    r = run("UNPAID_EXPIRY_RETRY")
    denied = next(x for x in r["journal"] if x["outcome"]["status"] == "REFUSED")
    o = next(o for o in denied["owners_after"] if o["operator"] == 0)
    check("unpaid work reserves full notional until expiry", o["reserved_payment_units"] == "100" and o["active_lead_net_units"] == "0")
    check("expiry admits a same-tick retry without consuming refused consent", r["metrics"]["agreements_opened"] == 2)
    r = run("PARTIAL_AND_FULL_RETURN")
    denied = next(x for x in r["journal"] if x["outcome"]["status"] == "REFUSED")
    o = next(o for o in denied["owners_after"] if o["operator"] == 0)
    check("partial return keeps full reservation while showing exact remaining payment",
          o["reserved_payment_units"] == "100" and o["active_lead_net_units"] == "70")
    check("observed full return permits retry without invented work credit",
          r["metrics"]["agreements_opened"] == 2 and r["metrics"]["voluntary_returns_recorded"] == "100" and
          all(not w["credit_shares"] for w in r["recovery"]["trust"]["contracts"]))
    r = run("LATE_RECEIPT_OVERAGE"); o = owner(r)
    check("valid late receipts remain recorded above both limits",
          r["metrics"]["payments_recorded"] == "200" and o["over_work_limit"] and o["over_payment_limit"] and o["dispute_hold"])
    check("late-payment hold does not create a refund", r["metrics"]["voluntary_returns_recorded"] == "0")
    r = run("DISPUTE_HOLD_PROPAGATION")
    check("peer dispute blocks new group admission only under owner risk policy",
          r["metrics"]["owner_rejections"] == 1 and run("DISPUTE_HOLD_PROPAGATION", "OWNER_COUNT")["metrics"]["owner_rejections"] == 0)
    check("accepted review and maturity restore admission", not owner(r)["dispute_hold"] and
          r["recovery"]["cases"][0]["status"] == "FINAL_ACCEPTED" and any(g["id"] == 9 for g in r["recovery"]["trust"]["groups"]))
    r = run("COLLECTIVE_SAME_OWNER")
    check("same-owner group counts its agreement once", r["metrics"]["agreements_opened"] == 1 and r["metrics"]["owner_rejections"] == 1)
    check("collective 60/40 credit remains exact and payment remains lead-only",
          r["recovery"]["trust"]["profiles"][0]["earned_credit_microunits"] == 606000 and
          r["recovery"]["trust"]["profiles"][5]["earned_credit_microunits"] == 404000 and
          r["recovery"]["trust"]["direct"]["agreements"][0]["terms"]["provider"] == 0)
    r = run("COLLECTIVE_DIFFERENT_OWNERS")
    check("different owners receive full assignment charges without inventing member payouts",
          sum(int(o["active_assigned_net_units"]) for o in r["owners"]) == 300 and
          sum(int(o["active_lead_net_units"]) for o in r["owners"]) == 200 and owner(r, 3)["active_lead_net_units"] == "0")
    check("unrelated declared owner remains able to work", r["metrics"]["agreements_opened"] == 2 and r["metrics"]["owner_rejections"] == 0)
    r = run("OWNER_DOWNGRADE"); o = owner(r)
    check("downgrade keeps four existing paid agreements visible", o["work_limit"] == 1 and len(o["active_agreements"]) == 4 and o["over_work_limit"])
    check("downgrade creates no return or confiscation", r["metrics"]["payments_recorded"] == "900" and r["metrics"]["voluntary_returns_recorded"] == "0")
    r = run("UNVERIFIED_ALIAS")
    check("owner tier does not transfer individual verification", owner(r)["tier"] == 1 and
          r["recovery"]["trust"]["profiles"][5]["tier"] == 0 and not r["recovery"]["trust"]["profiles"][5]["review_fixture_approved"])
    r = run("LARGE_EXACT_TOTALS", "OWNER_COUNT")
    check("u128 money totals and CSV digits remain exact above u64", r["metrics"]["payments_recorded"] == str(200 + 2 * (2**64-1)) and
          any(row["run_total_payments"] == r["metrics"]["payments_recorded"] for row in rows))
    check("hidden common control still bypasses declared owner labels", agreements("HIDDEN_COMMON_CONTROL") == 3)
    check("all direct receipt and return commands bypass owner admission gate", all(
          row["outcome"]["status"] == "FORWARDED" for r in runs.values() for row in r["journal"]
          if row["action"]["command"]["type"] == "TRUST" and row["action"]["command"]["command"]["type"] == "DIRECT"))
    check("all wallet capability flags remain false", all(not any(r["recovery"]["trust"]["direct"]["wallet_boundary"].values()) for r in runs.values()))
    # Canonical inner reports must also pass the earlier standalone CLI, without an owner context.
    for policy in POLICIES:
        path = temp / (policy + "-inner.json")
        path.write_text(json.dumps(run("DECLARED_WALLET_ROTATION", policy)["recovery"]), encoding="utf-8")
        cli("replay-recovery", path)
        check(policy + " inner recovery history independently replays through the earlier CLI")
    base = run("DECLARED_WALLET_ROTATION")
    mutations = {}
    f = copy.deepcopy(base); f["owners"][0]["reserved_payment_units"] = "0"; mutations["erased-reservation"] = f
    f = copy.deepcopy(base); f["journal"][0]["owners_after"][0]["work_limit"] = 100; mutations["inflated-capacity"] = f
    f = copy.deepcopy(base); f["journal"][0]["advance_sequence"] += 1; mutations["wrong-clock-link"] = f
    f = copy.deepcopy(base); f["journal"][0]["delegated_sequence"] += 1; mutations["wrong-delegation-link"] = f
    f = copy.deepcopy(base); f["metrics"]["payments_recorded"] = "301"; mutations["invented-payment"] = f
    f = copy.deepcopy(base); f["input"]["policy"] = "AGENT_ONLY"; mutations["changed-admission-policy"] = f
    f = copy.deepcopy(run("DISPUTE_HOLD_PROPAGATION"))
    next(o for row in f["journal"] if row["outcome"]["status"] == "REFUSED" for o in row["owners_after"] if o["operator"] == 0)["dispute_hold"] = False
    mutations["hidden-peer-hold"] = f
    for label, f in mutations.items():
        f["fingerprint"] = run_hash(f)
        path = temp / (label + ".json"); path.write_text(json.dumps(f), encoding="utf-8")
        cli("replay-owner", path, ok=False); rejects(inspect_run, f)
        check("native replay and independent audit reject rehashed " + label)
    for label in ["missing-case", "reordered-policies", "unmatched-action-prefix"]:
        f = copy.deepcopy(data)
        if label == "missing-case": f["cases"].pop()
        elif label == "reordered-policies": f["cases"][0]["runs"].reverse()
        else: f["cases"][0]["actions"].pop()
        f["fingerprint"] = campaign_hash(f)
        path = temp / (label + ".json"); path.write_text(json.dumps(f), encoding="utf-8")
        cli("replay-owner-campaign", path, ok=False)
        output = temp / (label + ".csv"); cli("owner-csv", path, output, ok=False)
        rejects(inspect_campaign, f)
        check(label + " cannot replay, audit or export", not output.exists())
    p = subprocess.run([sys.executable, "-O", str(ROOT / "scripts/owner_audit.py"), str(campaign)],
                       text=True, capture_output=True, timeout=120)
    check("Python optimization cannot disable independent assertions", p.returncode != 0 and "without -O" in p.stderr)
    original = campaign.read_bytes()
    cli("owner-campaign", ROOT / "configs/owner-campaign.toml", campaign, ok=False)
    check("existing report cannot be overwritten", campaign.read_bytes() == original)
    for label, change in [
        ("past-time", lambda i: i["actions"].append(i["actions"][0])),
        ("unknown-field", lambda i: i.update(hidden_override=True)),
        ("excess-actions", lambda i: i.update(actions=[i["actions"][0]] * 2049)),
        ("zero-cap", lambda i: i["config"].update(payment_caps=[0, 300, 1000])),
        ("decreasing-cap", lambda i: i["config"].update(payment_caps=[100, 99, 1000])),
        ("invalid-timing", lambda i: i["config"]["recovery"].update(evidence_ticks=0)),
        ("duplicate-reviewer", lambda i: i["config"]["recovery"]["reviewers"][1].update(id=0))]:
        value = copy.deepcopy(base["input"]); change(value)
        source, output = temp / (label + "-input.json"), temp / (label + "-output.json")
        source.write_text(json.dumps(value), encoding="utf-8")
        result = cli("owner-run", source, output, ok=False)
        check(label + " fails cleanly without output", result.returncode == 1 and "panicked" not in result.stderr and not output.exists())
    for label in ["valid-demo-timing", "valid-demo-panel"]:
        cfg = (ROOT / "configs/owner-campaign.toml").read_text(encoding="utf-8")
        cfg = cfg.replace("maturity_ticks = 3", "maturity_ticks = 6") if label == "valid-demo-timing" else cfg.replace("{id=4,operator=102}", "{id=4,operator=100}")
        source, output = temp / (label + ".toml"), temp / (label + ".json")
        source.write_text(cfg, encoding="utf-8")
        result = cli("owner-campaign", source, output, ok=False)
        check(label + " fails cleanly without a panic or report", result.returncode == 1 and "panicked" not in result.stderr and not output.exists())
head = os.environ.get("SOURCE_HEAD_SHA") or subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip()
summary = dict(source_head_sha=head, source_tree_dirty=bool(subprocess.check_output(["git", "status", "--porcelain"], cwd=ROOT)),
               classification="SYNTHETIC", model=data["model"], platform=platform.platform(), fingerprint=data["fingerprint"],
               independently_audited=counts, csv_owner_rows=len(rows), checks=CHECKS,
               report_sha256=hashlib.sha256(campaign.read_bytes()).hexdigest(),
               csv_sha256=hashlib.sha256(export.read_bytes()).hexdigest(), elapsed_seconds=round(time.perf_counter()-start, 3),
               timing_scope="SINGLE_ACCEPTANCE_SAMPLE_NOT_LIVE_THROUGHPUT", network_or_signer=False)
(OUT / "owner-evidence.json").write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
print(json.dumps(summary, indent=2))
