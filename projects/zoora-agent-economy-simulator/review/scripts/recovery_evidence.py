"""Actual CLI and independent AE-017 review/recovery acceptance evidence."""
from __future__ import annotations
import copy
import csv
import gzip
import hashlib
import io
import json
import os
import platform
import subprocess
import sys
import tempfile
import time
from pathlib import Path
from recovery_audit import inspect_campaign, inspect_run, run_hash, campaign_hash
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/"target/validation-evidence"
OUT.mkdir(parents=True,exist_ok=True)
NAME="zoora-review-market"+(".exe" if os.name=="nt" else "")
EXPECTED="85a846c501f22791e8d299684b7877ba3f6ced09959361f1a429a3b0058d61da"
CHECKS=[]

def check(label,condition=True):
    assert condition,label
    CHECKS.append(label)

def cli(*args,profile="release",ok=True):
    p=subprocess.run([str(ROOT/"target"/profile/NAME),*map(str,args)],cwd=ROOT,text=True,capture_output=True,timeout=120)
    assert (p.returncode==0)==ok,(args,p.stdout[-500:],p.stderr[-1500:])
    return p

start=time.perf_counter()
with tempfile.TemporaryDirectory() as folder:
    temp=Path(folder)
    campaign=OUT/"recovery-campaign.json"
    cli("recovery-campaign",ROOT/"configs/recovery-campaign.toml",campaign)
    cli("replay-recovery-campaign",campaign)
    data=json.loads(campaign.read_bytes())
    counts=inspect_campaign(data)
    check("15 full recovery histories independently audited",len(data["cases"])==15)
    check("reference fingerprint is pinned",data["fingerprint"]==EXPECTED)
    check("retained complete archive equals regenerated bytes",gzip.decompress((ROOT/"examples/recovery-campaign.json.gz").read_bytes())==campaign.read_bytes())
    debug=temp/"debug.json"
    cli("recovery-campaign",ROOT/"configs/recovery-campaign.toml",debug,profile="debug")
    check("normal and optimized builds produce identical histories",debug.read_bytes()==campaign.read_bytes())
    runs={c["name"]:c["run"] for c in data["cases"]}
    for name,run in runs.items():
        source,output=temp/(name+"-input.json"),temp/(name+"-output.json")
        source.write_text(json.dumps(run["input"]),encoding="utf-8")
        cli("recovery-run",source,output);cli("replay-recovery",output)
        value=json.loads(output.read_bytes());assert value==run;inspect_run(value)
        check(name+" actual CLI input reproduces all actions and case events")
    export=OUT/"recovery-campaign.csv"
    cli("recovery-csv",campaign,export)
    rows=list(csv.DictReader(io.StringIO(export.read_text(encoding="utf-8"))))
    check("CSV conserves all 16 worker-case rows and credit denominators",len(rows)==16 and all(r["credit_denominator"]=="10000" for r in rows))
    check("CSV retains run and campaign fingerprints",all(r["campaign_fingerprint"]==data["fingerprint"] and r["run_fingerprint"]==runs[r["case"]]["fingerprint"] for r in rows))
    check("retained CSV matches actual export",export.read_bytes()==(ROOT/"examples/recovery-campaign.csv").read_bytes())
    p=lambda name,agent=0:runs[name]["trust"]["profiles"][agent]
    status=lambda name:runs[name]["cases"][0]["status"]
    check("false complaint dismissal restores tier one",status("FALSE_COMPLAINT_DISMISSED")=="FINAL_ACCEPTED" and p("FALSE_COMPLAINT_DISMISSED")["tier"]==1)
    r=runs["CUSTOMER_NONRESPONSE_ACCEPTED"]
    check("reviewed nonresponse earns credit without inventing client acknowledgment",p("CUSTOMER_NONRESPONSE_ACCEPTED")["earned_credit_microunits"]==1_000_000 and not r["trust"]["direct"]["agreements"][0]["delivery_acknowledged"])
    check("upheld complaint retains paid exposure",status("COMPLAINT_UPHELD")=="FINAL_REJECTED" and p("COMPLAINT_UPHELD")["dispute_hold"] and p("COMPLAINT_UPHELD")["active_contracts"]==1)
    check("independent appeal can overturn a provisional rejection",status("APPEAL_OVERTURNS_REJECTION")=="FINAL_ACCEPTED" and runs["APPEAL_OVERTURNS_REJECTION"]["cases"][0]["primary"]["verdict"]=="REJECT_WORK")
    check("appeal can uphold a complaint",status("APPEAL_UPHOLDS_COMPLAINT")=="FINAL_REJECTED")
    check("one primary timeout reassigns review to another operator",runs["REVIEWER_TIMEOUT_ESCALATION"]["cases"][0]["primary_assignments"]==[1,3])
    check("all reviewer timeouts remain unresolved",all(status(n)=="EXPIRED" and p(n)["dispute_hold"] and p(n)["earned_credit_microunits"]==0 for n in ["REVIEWERS_ALL_TIMEOUT","APPEAL_TIMEOUT_UNRESOLVED"]))
    check("observed full return releases hold without work credit",status("RETURN_RESOLVES_PENDING")=="RETURNED" and not p("RETURN_RESOLVES_PENDING")["dispute_hold"] and p("RETURN_RESOLVES_PENDING")["earned_credit_microunits"]==0)
    check("partial return invalidates provisional acceptance",status("STALE_ACCEPTANCE")=="STALE" and p("STALE_ACCEPTANCE")["dispute_hold"])
    check("group work restoration keeps 60/40 shares exact",p("COLLECTIVE_CONTESTED")["earned_credit_microunits"]==606_000 and p("COLLECTIVE_CONTESTED",3)["earned_credit_microunits"]==404_000)
    check("review never creates a financial return",all(int(r["trust"]["direct"]["metrics"]["voluntary_refunds_recorded"])==(100 if n=="RETURN_RESOLVES_PENDING" else 1 if n=="STALE_ACCEPTANCE" else 0) for n,r in runs.items()))
    check("all wallet capability flags remain false",all(not any(r["trust"]["direct"]["wallet_boundary"].values()) for r in runs.values()))
    # Tick zero is valid: an observed return at zero must not mean "absent".
    zero=copy.deepcopy(runs["RETURN_RESOLVES_PENDING"]["input"])
    for action in zero["actions"]:
        action["tick"]=0
        command=action["command"]
        if command["type"]=="TRUST" and command["command"]["type"]=="DIRECT":
            receipt=command["command"]["command"].get("receipt")
            if receipt is not None:
                receipt.update(availability_tick=0,simulation_tick=0)
    source,output=temp/"zero-input.json",temp/"zero-run.json"
    source.write_text(json.dumps(zero),encoding="utf-8")
    cli("recovery-run",source,output);cli("replay-recovery",output)
    zero=json.loads(output.read_bytes());inspect_run(zero)
    check("legitimate tick-zero return is independently auditable",zero["cases"][0]["returned_tick"]==0)
    duplicate=copy.deepcopy(zero)
    index=next(i for i,e in enumerate(duplicate["events"]) if e["kind"]=="RETURN_OBSERVED")
    duplicate["events"].insert(index+1,copy.deepcopy(duplicate["events"][index]))
    for i,event in enumerate(duplicate["events"]):event["sequence"]=i
    for row in duplicate["journal"]:
        if row["event_count_after"]>index:row["event_count_after"]+=1
    duplicate["fingerprint"]=run_hash(duplicate)
    path=temp/"duplicate-zero-return.json";path.write_text(json.dumps(duplicate),encoding="utf-8")
    cli("replay-recovery",path,ok=False)
    try:inspect_run(duplicate)
    except AssertionError:pass
    else:raise AssertionError("duplicate tick-zero return passed independent audit")
    check("native replay and independent audit reject duplicate tick-zero return")
    base=runs["APPEAL_OVERTURNS_REJECTION"]
    mutations={}
    f=copy.deepcopy(base);f["cases"][0]["appellate_reviewer"]=2;mutations["conflicted-final-reviewer"]=f
    f=copy.deepcopy(base);f["events"][0]["visible_actions"]+=1;mutations["future-evidence-prefix"]=f
    f=copy.deepcopy(base);f["events"][-1]["case"]["appellate"]["binding"]="a"*64;mutations["false-work-binding"]=f
    f=copy.deepcopy(base);f["trust"]["contracts"][0]["credit_shares"][0]["earned_microunits"]+=1;mutations["extra-work-credit"]=f
    f=copy.deepcopy(base);f["journal"][0]["profiles_after"][0]["tier"]=2;mutations["forged-admission-history"]=f
    f=copy.deepcopy(base);f["trust"]["direct"]["metrics"]["voluntary_refunds_recorded"]="100";mutations["invented-financial-return"]=f
    for label,f in mutations.items():
        f["fingerprint"]=run_hash(f);path=temp/(label+".json");path.write_text(json.dumps(f),encoding="utf-8")
        cli("replay-recovery",path,ok=False)
        try:inspect_run(f)
        except (AssertionError,KeyError):pass
        else:raise AssertionError("independent audit accepted "+label)
        check("native replay and independent audit reject rehashed "+label)
    for label,change in [("missing-case",lambda f:f["cases"].pop()),("reordered-cases",lambda f:f["cases"].reverse())]:
        f=copy.deepcopy(data);change(f);f["fingerprint"]=campaign_hash(f)
        path=temp/(label+".json");path.write_text(json.dumps(f),encoding="utf-8")
        cli("replay-recovery-campaign",path,ok=False);export_bad=temp/(label+".csv");cli("recovery-csv",path,export_bad,ok=False)
        check(label+" cannot replay or export",not export_bad.exists())
    command=[sys.executable,"-O",str(ROOT/"scripts/recovery_audit.py"),str(campaign)]
    p=subprocess.run(command,text=True,capture_output=True,timeout=120)
    check("Python optimization cannot disable independent assertions",p.returncode!=0 and "without -O" in p.stderr)
    original=campaign.read_bytes();cli("recovery-campaign",ROOT/"configs/recovery-campaign.toml",campaign,ok=False)
    check("existing report cannot be overwritten",campaign.read_bytes()==original)
    for label,change in [
        ("past-time",lambda i:i["actions"].append(i["actions"][0])),
        ("unknown-input-field",lambda i:i.update(hidden_override=True)),
        ("excess-actions",lambda i:i.update(actions=[i["actions"][0]]*4097)),
        ("invalid-timing",lambda i:i["config"].update(evidence_ticks=0)),
        ("duplicate-reviewer-id",lambda i:i["config"]["reviewers"][1].update(id=0))]:
        value=copy.deepcopy(base["input"]);change(value)
        source,output=temp/(label+"-input.json"),temp/(label+"-output.json")
        source.write_text(json.dumps(value),encoding="utf-8");cli("recovery-run",source,output,ok=False)
        check(label+" rejected without output creation",not output.exists())
    for label in ["valid-demo-timing","valid-demo-panel"]:
        # This mode takes TOML, so preserve the documented reference and vary one setting.
        cfg=(ROOT/"configs/recovery-campaign.toml").read_text(encoding="utf-8")
        cfg=cfg.replace("maturity_ticks = 3","maturity_ticks = 6") if label=="valid-demo-timing" else cfg.replace("{id=4,operator=102}","{id=4,operator=100}")
        source,output=temp/(label+".toml"),temp/(label+".json")
        source.write_text(cfg,encoding="utf-8")
        result=cli("recovery-campaign",source,output,ok=False)
        check(label+" fails cleanly without a panic or report",result.returncode==1 and "panicked" not in result.stderr and not output.exists())
head=os.environ.get("SOURCE_HEAD_SHA") or subprocess.check_output(["git","rev-parse","HEAD"],cwd=ROOT,text=True).strip()
summary=dict(source_head_sha=head,source_tree_dirty=bool(subprocess.check_output(["git","status","--porcelain"],cwd=ROOT)),classification="SYNTHETIC",model=data["model"],platform=platform.platform(),fingerprint=data["fingerprint"],independently_audited=counts,checks=CHECKS,report_sha256=hashlib.sha256(campaign.read_bytes()).hexdigest(),csv_sha256=hashlib.sha256(export.read_bytes()).hexdigest(),elapsed_seconds=round(time.perf_counter()-start,3),timing_scope="SINGLE_ACCEPTANCE_SAMPLE_NOT_LIVE_THROUGHPUT",network_or_signer=False)
(OUT/"recovery-evidence.json").write_text(json.dumps(summary,indent=2)+"\n",encoding="utf-8")
print(json.dumps(summary,indent=2))
